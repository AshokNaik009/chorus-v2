#!/usr/bin/env node
/**
 * Turn `packages/detect/manifests/*.toml` into a TypeScript module.
 *
 * ## Why generate instead of reading the files at runtime
 *
 * PHASE-5 Part C ships the app through a bundler, and the one thing a bundler cannot
 * do is resolve a path computed at runtime — that is the whole node-pty trap, and a
 * `readFileSync(join(__dirname, 'manifests', `${id}.toml`))` is the same shape of
 * mistake. Bundled manifests are *data the build knows about*, so they are string
 * constants and the built app has no manifest directory to lose.
 *
 * User overrides are still read from disk at runtime, because their path is the user's
 * and cannot be known at build time. That is the difference.
 *
 * Run: `node scripts/generate-bundled-manifests.mjs`
 * Checked by: `packages/detect/src/bundled.test.ts`, which fails if this was not run.
 */

import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const manifestDir = join(root, 'packages/detect/manifests')
const outputPath = join(root, 'packages/detect/src/bundled.ts')

export function renderBundledManifests() {
  const names = readdirSync(manifestDir)
    .filter((name) => name.endsWith('.toml'))
    .sort()

  const entries = names.map((name) => {
    const id = name.replace(/\.toml$/, '')
    const body = readFileSync(join(manifestDir, name), 'utf8')
    return `  [\n    ${JSON.stringify(id)},\n    ${JSON.stringify(body)}\n  ]`
  })

  return `/**
 * Bundled manifests, as data.
 *
 * GENERATED by \`scripts/generate-bundled-manifests.mjs\` from
 * \`packages/detect/manifests/*.toml\`. Edit the TOML, then re-run the script;
 * \`bundled.test.ts\` fails if the two disagree.
 */

/** Manifest id -> TOML source. Ordered by id so the generated file is stable. */
export const BUNDLED_MANIFESTS: readonly (readonly [string, string])[] = [
${entries.join(',\n')}
]

export const BUNDLED_MANIFEST_IDS: readonly string[] = BUNDLED_MANIFESTS.map(([id]) => id)
`
}

if (process.argv[1] && import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(outputPath, renderBundledManifests())
  console.log(`wrote ${outputPath}`)
}
